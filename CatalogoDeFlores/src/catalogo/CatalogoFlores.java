    private void carregarPlanta(int id) {

        FlorDAO dao = new FlorDAO();

        ResultSet rs = dao.buscarPorId(id);

        try {

            if (rs.next()) {

                txfNome.setText(rs.getString("nome"));
                txfNomeCientifico.setText(rs.getString("nomecientifico"));
                cmbTipo.setSelectedItem(rs.getString("tipo"));
                txfCor.setText(rs.getString("cor"));
                txfAltMedia.setText(
                        String.valueOf(rs.getDouble("altura"))
                );
                txfEmail.setText(rs.getString("email"));
            }

        } catch (SQLException e) {

            JOptionPane.showMessageDialog(this,
                    "Erro ao carregar planta: " + e.getMessage());
        }
    }


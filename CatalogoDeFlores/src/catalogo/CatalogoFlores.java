    private void btnCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCadastrarActionPerformed
    if (txfNome.getText().isEmpty()
            || txfNomeCientifico.getText().isEmpty()
            || txfCor.getText().isEmpty()
            || txfAltMedia.getText().isEmpty()) {

        JOptionPane.showMessageDialog(this,
                "Preencha todas as informações!");
        return;
    }

    if (!btnradPequena.isSelected()
            && !btnradMedia.isSelected()
            && !btnradGrande.isSelected()) {

        JOptionPane.showMessageDialog(this,
                "Selecione o tamanho da planta!");
        return;
    }

    if (!ckbSol.isSelected()
            && !ckbSombra.isSelected()
            && !ckbMeiaSombra.isSelected()) {

        JOptionPane.showMessageDialog(this,
                "Selecione a necessidade de sol!");
        return;
    }

    double altura;

    try {

        altura = Double.parseDouble(txfAltMedia.getText());

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(this,
                "A altura deve conter apenas números!");
        return;
    }

    String cor = txfCor.getText();

    if (!cor.matches("[a-zA-ZÀ-ÿ ]+")) {

        JOptionPane.showMessageDialog(this,
                "A cor deve conter apenas letras!");
        return;
    }

    String email = txfEmail.getText();

    if (!email.matches("^[A-Za-z0-9+_.-]+@[A-Za-z0-9.-]+\\.com$")) {

        JOptionPane.showMessageDialog(this,
                "Digite um e-mail válido com .com!");
        return;
    }

    String tamanho = "";

    if (btnradPequena.isSelected()) {
        tamanho = "Pequena";

    } else if (btnradMedia.isSelected()) {
        tamanho = "Média";

    } else if (btnradGrande.isSelected()) {
        tamanho = "Grande";
    }

    String necessidadeSol = "";

    if (ckbSol.isSelected()) {
        necessidadeSol += "Sol pleno";
    }

    if (ckbSombra.isSelected()) {

        if (!necessidadeSol.isEmpty()) {
            necessidadeSol += ", ";
        }

        necessidadeSol += "Sombra";
    }

    if (ckbMeiaSombra.isSelected()) {

        if (!necessidadeSol.isEmpty()) {
            necessidadeSol += ", ";
        }

        necessidadeSol += "Meia-sombra";
    }

    Flor f = new Flor();

    f.setNome(txfNome.getText());
    f.setNomeCientifico(txfNomeCientifico.getText());
    f.setTipo(cmbTipo.getSelectedItem().toString());
    f.setCor(cor);
    f.setAltura(altura);
    f.setTamanho(tamanho);
    f.setNecessidadeSol(necessidadeSol);
    f.setEmail(email);
    f.setFoto(caminhoFoto);
    
    String caminhoPDF = pdf.GeradorPDF.gerarPDF(f);

    FlorDAO fDAO = new FlorDAO();

    if (idEdicao != 0) {

        fDAO.atualizar(f, idEdicao);

        JOptionPane.showMessageDialog(this,
                "Planta atualizada com sucesso!");

    } else {

        fDAO.inserir(f);

        JOptionPane.showMessageDialog(this,
                "Planta cadastrada com sucesso!");
    }

    Registros registros = new Registros();

    registros.setVisible(true);

    this.dispose();
              
    }//GEN-LAST:event_btnCadastrarActionPerformed
 
    
    String caminhoFoto = "";
    private void btnEscolherFotoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEscolherFotoActionPerformed
        JFileChooser arquivo = new JFileChooser();
    if (arquivo.showOpenDialog(this) == JFileChooser.APPROVE_OPTION) {
        File origem = arquivo.getSelectedFile();
        File pasta = new File("fotos");
    if (!pasta.exists()) {
        pasta.mkdir();
    }
    File destino = new File(pasta, origem.getName());
    try {
        Files.copy(
                origem.toPath(),
                destino.toPath(),
                java.nio.file.StandardCopyOption.REPLACE_EXISTING
        );
        caminhoFoto = destino.getPath();
        ImageIcon imagem = new ImageIcon(caminhoFoto);
        Image img = imagem.getImage();
        img = img.getScaledInstance(
                lblFotoDaFlor.getWidth(),
                lblFotoDaFlor.getHeight(),
                Image.SCALE_SMOOTH
        );
        lblFotoDaFlor.setIcon(new ImageIcon(img));
    } catch (IOException e) {
        JOptionPane.showMessageDialog(this,
                "Erro ao salvar a foto: " + e.getMessage());
    }
}
    }//GEN-LAST:event_btnEscolherFotoActionPerformed

